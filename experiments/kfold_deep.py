"""Reduced k-fold rep for the deep hybrid ST-MoE (paper rigor, GPU-bounded).

The full deep k-fold (5 folds x 3 seeds) is ~10 GPU-hours, so this runs a REDUCED rep:
the first ``n_use`` folds of the seed-42 5-fold partition — the *same* held-out wells as
``kfold_eval.py`` seed=42 folds 0..n, so the GBT and hybrid numbers are directly comparable.

Each fold reuses the tested ``run_stmoe`` (streaming + hybrid) via its new ``split`` arg,
and records all-source AND real-only metrics. Writes docs/paper/results_kfold_deep.md.

Usage: uv run python experiments/kfold_deep.py [n_use_folds] [seed]   (defaults: 3, 42)
"""

from __future__ import annotations

import json
import os
import sys

import numpy as np

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "src"))

from config import load_data_config, load_features_config, load_model_config  # noqa: E402
from dataset.splitter import WellDisjointSplitter  # noqa: E402
from ingest import discover_instances  # noqa: E402
from pipeline import run_stmoe  # noqa: E402
from schema import EventClass  # noqa: E402

NAMES = [EventClass(i).name for i in range(10)]


def _mean_std(vals: list[float]) -> tuple[float, float]:
    a = np.asarray([v for v in vals if v is not None], dtype=float)
    return (float(a.mean()), float(a.std())) if len(a) else (float("nan"), float("nan"))


def main() -> None:
    n_use = int(sys.argv[1]) if len(sys.argv) > 1 else 3
    seed = int(sys.argv[2]) if len(sys.argv) > 2 else 42

    dcfg, fcfg, mcfg = load_data_config(), load_features_config(), load_model_config()
    mcfg.window.stride_s = 300.0  # stride-300 keeps each fold ~40 min (vs ~70 for 150)
    mcfg.train.epochs = 30
    mcfg.train.batch_size = 256
    mcfg.train.ssl_epochs = 0  # SSL hurts classification (see docs/ablations.md)

    metas = discover_instances(dcfg)
    folds = list(WellDisjointSplitter(seed=seed).k_folds(metas, 5))[:n_use]
    print(
        f"### deep hybrid rep: {n_use} folds (seed {seed}), stride-300, hybrid, no-SSL", flush=True
    )

    recs: list[dict] = []
    for k, split in enumerate(folds):
        print(f"### fold {k}: training hybrid...", flush=True)
        m = run_stmoe(dcfg, fcfg, mcfg, streaming=True, hybrid=True, split=split, progress=False)
        recs.append(m)
        print(
            f"### fold {k}: macro-F1={m['macro_f1']:.4f}"
            f"  real={m.get('macro_f1_real')}"
            f"  FLOW_INST={m['per_class_f1']['FLOW_INSTABILITY']:.3f}",
            flush=True,
        )

    mm, msd = _mean_std([r["macro_f1"] for r in recs])
    rm, rsd = _mean_std([r.get("macro_f1_real") for r in recs])
    print(
        f"\n### hybrid macro-F1 over {len(recs)} folds: all={mm:.4f}+/-{msd:.4f}"
        f"  real={rm:.4f}+/-{rsd:.4f}",
        flush=True,
    )

    lines = [
        "# Reduced k-fold deep hybrid results\n",
        f"{len(recs)} folds (seed {seed} of a 5-fold partition — same held-out wells as the GBT "
        "k-fold seed=42 folds), stride-300, hybrid, no-SSL, fusion+gating. "
        "Auto-generated by `experiments/kfold_deep.py`.\n",
        f"**macro-F1 all-source: {mm:.4f} +/- {msd:.4f}**  |  "
        f"**real-only: {rm:.4f} +/- {rsd:.4f}**\n",
        "| class | F1 all (mean+/-std) | F1 real (mean+/-std) |",
        "|---|---|---|",
    ]
    for i in range(10):
        c = NAMES[i]
        am, asd = _mean_std([r["per_class_f1"][c] for r in recs])
        rvals = [
            r["per_class_f1_real"].get(c) for r in recs if r.get("support_real", {}).get(c, 0) > 0
        ]
        rstr = f"{np.mean(rvals):.3f} +/- {np.std(rvals):.3f}" if rvals else "— (no real data)"
        lines.append(f"| {c} | {am:.3f} +/- {asd:.3f} | {rstr} |")

    os.makedirs("docs/paper", exist_ok=True)
    with open("docs/paper/results_kfold_deep.md", "w") as fh:
        fh.write("\n".join(lines) + "\n")
    with open("docs/paper/results_kfold_deep.json", "w") as fh:
        json.dump(
            [{k: v for k, v in r.items() if k != "confusion"} for r in recs],
            fh,
            indent=2,
            default=str,
        )
    print("### wrote docs/paper/results_kfold_deep.md")


if __name__ == "__main__":
    main()
