"""K-fold x multi-seed well-disjoint evaluation harness (paper rigor).

Builds the windowed feature dataset ONCE over *all* instances, then evaluates the GBT
across well-disjoint folds and seeds, reporting mean+/-std macro-F1, per-class F1, and
REAL-ONLY per-class F1 (computed only on folds where the class has real test data).

Writes docs/paper/results_kfold.md (+ .json). Reuses src.dataset.WellDisjointSplitter.

Usage:
  uv run python experiments/kfold_eval.py [n_folds] [seed1,seed2,...]
  (defaults: 5 folds, seeds 42,1,2)
"""

from __future__ import annotations

import json
import os
import sys

import numpy as np

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "src"))

from config import load_data_config, load_features_config, load_model_config  # noqa: E402
from dataset.build import build_window_dataset  # noqa: E402
from dataset.splitter import WellDisjointSplitter  # noqa: E402
from eval.metrics import classification_report  # noqa: E402
from ingest import discover_instances  # noqa: E402
from models.baseline import GBTClassifier  # noqa: E402
from pipeline import _cap_per_class  # noqa: E402
from schema import EventClass  # noqa: E402

NAMES = [EventClass(i).name for i in range(10)]


def _mean_std(vals: list[float]) -> tuple[float, float]:
    a = np.asarray(vals, dtype=float)
    return float(a.mean()), float(a.std())


def main() -> None:
    n_folds = int(sys.argv[1]) if len(sys.argv) > 1 else 5
    seeds = [int(s) for s in sys.argv[2].split(",")] if len(sys.argv) > 2 else [42, 1, 2]
    limit = int(sys.argv[3]) if len(sys.argv) > 3 else 0  # per-class cap for smoke tests (0=all)

    dcfg, fcfg, mcfg = load_data_config(), load_features_config(), load_model_config()
    mcfg.window.stride_s = 300.0
    metas = discover_instances(dcfg)
    if limit:
        metas = _cap_per_class(metas, limit, 42)
    print(f"### building window features for ALL {len(metas)} instances (once)...", flush=True)
    ds = build_window_dataset(metas, dcfg, fcfg, mcfg, progress=True)
    print(f"### built {len(ds)} windows x {ds.X.shape[1]} features", flush=True)
    wid, real = ds.well_id, (ds.source == "REAL")

    recs: list[dict] = []
    for seed in seeds:
        for k, split in enumerate(WellDisjointSplitter(seed=seed).k_folds(metas, n_folds)):
            trw = {m.well_id for m in split.train}
            tew = {m.well_id for m in split.test}
            trm = np.array([w in trw for w in wid])
            tem = np.array([w in tew for w in wid])
            clf = GBTClassifier(mcfg.baseline, seed=seed).fit(ds.X[trm], ds.event[trm])
            pred = clf.predict(ds.X[tem])
            rep = classification_report(ds.event[tem], pred)
            rr = real[tem]
            rep_real = classification_report(ds.event[tem][rr], pred[rr]) if rr.any() else None
            recs.append(
                {
                    "seed": seed,
                    "fold": k,
                    "macro_f1": rep.macro_f1,
                    "per_class": rep.per_class_f1,
                    "per_class_real": (rep_real.per_class_f1 if rep_real else {}),
                    "real_support": {NAMES[i]: int((ds.event[tem][rr] == i).sum()) for i in range(10)},
                }
            )
            print(
                f"### seed={seed} fold={k}: macro-F1={rep.macro_f1:.4f}"
                f"  FLOW_INST={rep.per_class_f1['FLOW_INSTABILITY']:.3f}",
                flush=True,
            )

    mm, msd = _mean_std([r["macro_f1"] for r in recs])
    print(f"\n### macro-F1 over {len(recs)} (seed x fold) reps: {mm:.4f} +/- {msd:.4f}", flush=True)

    lines = [
        "# K-fold x multi-seed results (GBT baseline)\n",
        f"{n_folds}-fold well-disjoint CV x seeds {seeds} = **{len(recs)} reps**. "
        "stride-300, de-leaked features. Auto-generated by `experiments/kfold_eval.py`.\n",
        f"**macro-F1 (all-source): {mm:.4f} +/- {msd:.4f}**\n",
        "| class | F1 all (mean+/-std) | F1 real (mean+/-std) | median real support |",
        "|---|---|---|---|",
    ]
    for i in range(10):
        c = NAMES[i]
        am, asd = _mean_std([r["per_class"][c] for r in recs])
        rvals = [r["per_class_real"][c] for r in recs if r["real_support"].get(c, 0) > 0]
        rstr = f"{np.mean(rvals):.3f} +/- {np.std(rvals):.3f}" if rvals else "— (no real data)"
        rsup = int(np.median([r["real_support"][c] for r in recs]))
        lines.append(f"| {c} | {am:.3f} +/- {asd:.3f} | {rstr} | {rsup} |")

    os.makedirs("docs/paper", exist_ok=True)
    with open("docs/paper/results_kfold.md", "w") as fh:
        fh.write("\n".join(lines) + "\n")
    with open("docs/paper/results_kfold.json", "w") as fh:
        json.dump(recs, fh, indent=2, default=str)
    print("### wrote docs/paper/results_kfold.md")


if __name__ == "__main__":
    main()
