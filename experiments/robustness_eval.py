"""Robustness probes (sensor freeze / channel dropout) for the paper (AGENT.md §7).

Trains a raw ST-MoE on the full-data stratified split, then re-scores macro-F1 with each
physical subsystem's channels perturbed in turn (dropout = zero, freeze = hold the first
value). Uses the *raw* (non-hybrid) model so the perturbation fully reaches the classifier
— the hybrid's engineered features are computed from the unperturbed signals and would
mask the sequence degradation. Writes docs/paper/results_robustness.md.

Usage: uv run python experiments/robustness_eval.py
"""

from __future__ import annotations

import contextlib
import os
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "src"))

import torch  # noqa: E402

from config import load_data_config, load_features_config, load_model_config  # noqa: E402
from dataset.build import build_sequence_memmap  # noqa: E402
from dataset.splitter import WellDisjointSplitter  # noqa: E402
from eval.robustness import robustness_probe  # noqa: E402
from ingest import discover_instances  # noqa: E402
from train.loop import train_stmoe  # noqa: E402


def main() -> None:
    dcfg, fcfg, mcfg = load_data_config(), load_features_config(), load_model_config()
    mcfg.window.stride_s = 300.0
    mcfg.train.epochs = 30
    mcfg.train.batch_size = 256
    mcfg.train.ssl_epochs = 0

    split = WellDisjointSplitter(seed=dcfg.seed).stratified_train_test_split(
        discover_instances(dcfg), test_frac=0.25
    )
    cache = Path(dcfg.runs_dir) / "_seqcache" / str(os.getpid())
    print("### building sequence datasets (raw, no features)...", flush=True)
    tr = build_sequence_memmap(split.train, dcfg, fcfg, mcfg, cache / "train.f16", progress=False)
    te = build_sequence_memmap(split.test, dcfg, fcfg, mcfg, cache / "test.f16", progress=False)
    try:
        net, _ = train_stmoe(tr, te, mcfg, runs_dir=dcfg.runs_dir)
        net.eval()
        dev = next(net.parameters()).device
        bs = mcfg.train.batch_size

        @torch.no_grad()
        def predict(X: np.ndarray) -> np.ndarray:
            out = []
            for i in range(0, len(X), bs):
                xb = torch.from_numpy(np.asarray(X[i : i + bs], dtype=np.float32)).to(dev)
                out.append(net(xb)["event"].argmax(-1).cpu().numpy())
            return np.concatenate(out)

        lines = [
            "# Robustness under sensor perturbation (raw ST-MoE, full data, stride-300)\n",
            "Per-subsystem channel perturbation; macro-F1 and Δ from clean. "
            "Auto-generated by `experiments/robustness_eval.py`.\n",
        ]
        for mode in ("dropout", "freeze"):
            res = robustness_probe(predict, te.X, te.event, mode=mode)
            lines += [
                f"## {mode}",
                f"clean macro-F1 = {res.baseline_macro_f1:.4f}\n",
                "| perturbation | macro-F1 | Δ |",
                "|---|---|---|",
            ]
            for k, v in res.perturbations.items():
                lines.append(f"| {k} | {v:.4f} | {v - res.baseline_macro_f1:+.4f} |")
            lines.append("")
            print(
                f"### {mode}: clean={res.baseline_macro_f1:.4f}  "
                + "  ".join(f"{k.split(':')[1]}={v:.3f}" for k, v in res.perturbations.items()),
                flush=True,
            )

        os.makedirs("docs/paper", exist_ok=True)
        with open("docs/paper/results_robustness.md", "w") as fh:
            fh.write("\n".join(lines) + "\n")
        print("### wrote docs/paper/results_robustness.md")
    finally:
        for f in ("train.f16", "test.f16"):
            (cache / f).unlink(missing_ok=True)
        with contextlib.suppress(OSError):
            cache.rmdir()


if __name__ == "__main__":
    main()
